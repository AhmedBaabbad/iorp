const { chromium } = require('../.tmp/prod-plan-browser/node_modules/playwright');
const fs = require('fs');
const path = require('path');
const out = path.resolve('docs/verification/prod-plan-001');
fs.mkdirSync(out, {recursive:true});
(async()=>{
 const browser = await chromium.launch({channel:'msedge',headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:1100}});
 page.setDefaultTimeout(30000);
 page.setDefaultNavigationTimeout(60000);
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3001/login');
 await Promise.all([page.waitForResponse(r=>r.url().includes('/system/bootstrap/status')),page.getByRole('button',{name:'English',exact:true}).click()]);
 await page.waitForLoadState('networkidle');
 await page.getByLabel('Email address',{exact:true}).fill('planner-prod-plan@example.com');
 await page.getByPlaceholder('Enter your password').fill('PlanReview123!');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await page.waitForURL('**/dashboard');
 await page.goto('http://localhost:3001/production/demands/new');
 await page.getByRole('heading',{name:'New Production Demand',exact:true}).waitFor();
 await page.getByLabel('Customer',{exact:true}).selectOption({label:'C-QA-001 · Rehana Packaging'});
 await page.getByLabel('Quote',{exact:true}).selectOption({label:'Q-QA-001'});
 await page.getByRole('button',{name:'Import Quote Items',exact:true}).click();
 await page.getByText('Imported 1 items',{exact:true}).waitFor();
 await page.screenshot({path:path.join(out,'01-create.png'),fullPage:true});
 await page.getByRole('button',{name:'Save and Mark Ready',exact:true}).click();
 await page.waitForURL(/\/production\/demands\/[0-9a-f-]+$/);
 await page.getByRole('heading',{name:'Items',exact:true}).waitFor();
 const detailUrl=page.url();
 await page.screenshot({path:path.join(out,'02-detail.png'),fullPage:true});
 await page.getByRole('link',{name:'Edit Production Demand',exact:true}).click();
 await page.getByRole('heading',{name:'Edit Production Demand',exact:true}).waitFor();
 await page.getByLabel('Quantity',{exact:true}).fill('750');
 await page.screenshot({path:path.join(out,'03-edit.png'),fullPage:true});
 await page.getByRole('button',{name:'Save Changes',exact:true}).click();
 await page.waitForURL(detailUrl);
 await page.getByRole('cell',{name:'750.000',exact:true}).waitFor();
 await page.goto('http://localhost:3001/production/demands');
 await page.getByRole('table').waitFor();
 await page.getByRole('cell',{name:'Rehana Packaging',exact:false}).first().waitFor();
 await page.screenshot({path:path.join(out,'04-list.png'),fullPage:true});
 await page.goto('http://localhost:3001/production/planning');
 await page.getByRole('cell',{name:'Rehana Packaging',exact:false}).first().waitFor();
 await page.screenshot({path:path.join(out,'05-planning.png'),fullPage:true});
 console.log((await page.locator('body').innerText()).slice(-2500));
 console.log('All five pages verified; imported snapshot edited from 500 to 750 kg.');
 fs.writeFileSync(path.join(out,'browser-errors.json'),JSON.stringify(errors,null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
