def country_sort_key(key: str, english: str):
    if key in ARAB_COUNTRIES:
        return (0, ARAB_COUNTRIES.index(key), "")
    name = "".join(c for c in normalize("NFKD", english.casefold()) if not combining(c))
    return (1, 0, name)
