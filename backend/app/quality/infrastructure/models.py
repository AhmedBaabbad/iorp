    report_type: Mapped[NCRReportType] = mapped_column(SqlEnum(NCRReportType, name="quality_ncr_report_type", values_callable=enum_values),
                                                       nullable=False, index=True)
    status: Mapped[str] = mapped_column(String(16), nullable=False, default="open", index=True)
    severity: Mapped[str] = mapped_column(String(12), nullable=False, default="major")
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    reference_code: Mapped[str | None] = mapped_column(String(255), nullable=True)  # a batch, lot, delivery or document reference
    # Sources (plain references).
    quality_check_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True, index=True)
    quality_rejection_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True, index=True)
    production_order_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True, index=True)
    return_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True, index=True)
    customer_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True, index=True)
    customer_name: Mapped[str | None] = mapped_column(String(255), nullable=True)
    supplier_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True, index=True)  # procurement, later
    supplier_name: Mapped[str | None] = mapped_column(String(255), nullable=True)
    supplier_reference: Mapped[str | None] = mapped_column(String(120), nullable=True)  # the supplier's delivery, invoice or lot
    # Who follows it up, and by when.
    owner_user_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("foundation_users.id"), nullable=True)
    due_date: Mapped[date | None] = mapped_column(nullable=True)
    # Containment: what was done at once to stop it spreading (quarantine, sorting, stopping a line…).
    containment: Mapped[str | None] = mapped_column(Text, nullable=True)
    contained_at: Mapped[datetime | None] = mapped_column(TZDateTime, nullable=True)
    contained_by_user_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("foundation_users.id"), nullable=True)
    # Investigation: the root cause (6M category, method, analysis), and whether a corrective action is needed.
    root_cause_category: Mapped[str | None] = mapped_column(String(16), nullable=True)
    root_cause_method: Mapped[str | None] = mapped_column(String(16), nullable=True)
    root_cause: Mapped[str | None] = mapped_column(Text, nullable=True)
    action_required: Mapped[bool | None] = mapped_column(Boolean, nullable=True)
    no_action_justification: Mapped[str | None] = mapped_column(Text, nullable=True)
    investigated_at: Mapped[datetime | None] = mapped_column(TZDateTime, nullable=True)
    investigated_by_user_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("foundation_users.id"), nullable=True)
    # Verification of the actions' effectiveness (repeated when they were not effective).
    verification_attempts: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    verification_notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    verified_at: Mapped[datetime | None] = mapped_column(TZDateTime, nullable=True)
    verified_by_user_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("foundation_users.id"), nullable=True)
    closed_at: Mapped[datetime | None] = mapped_column(TZDateTime, nullable=True)
    cancel_reason: Mapped[str | None] = mapped_column(Text, nullable=True)
    # With the responsible party (supplier or carrier): the action asked, and its answer.
    supplier_action: Mapped[str] = mapped_column(String(16), nullable=False, default="none")
    supplier_response: Mapped[str | None] = mapped_column(Text, nullable=True)
    supplier_responded_at: Mapped[date | None] = mapped_column(nullable=True)
    # Cost of the non-conformance (optional), and what is claimed back.
    cost_material: Mapped[Decimal | None] = mapped_column(Numeric(14, 2), nullable=True)
    cost_labor: Mapped[Decimal | None] = mapped_column(Numeric(14, 2), nullable=True)
    cost_scrap: Mapped[Decimal | None] = mapped_column(Numeric(14, 2), nullable=True)
    cost_transport: Mapped[Decimal | None] = mapped_column(Numeric(14, 2), nullable=True)
    cost_other: Mapped[Decimal | None] = mapped_column(Numeric(14, 2), nullable=True)
    claim_amount: Mapped[Decimal | None] = mapped_column(Numeric(14, 2), nullable=True)
    claim_status: Mapped[str] = mapped_column(String(12), nullable=False, default="none")
    detected_by_user_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("foundation_users.id"), nullable=False)
    created_at: Mapped[datetime] = mapped_column(TZDateTime, nullable=False, default=utc_now)
    updated_at: Mapped[datetime] = mapped_column(TZDateTime, nullable=False, default=utc_now, onupdate=utc_now)


