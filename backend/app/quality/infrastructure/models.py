class QualityCheck(Base):
    """Formal inspection event for a production lot, output, or sample.

    Status vs result separation (intentional design):
      - status  tracks the lifecycle of the INSPECTION PROCESS itself
                (open → under_inspection → closed).
      - result  records the OUTCOME of the inspection
                (accepted / rejected / conditional_accept / needs_reinspection).
      These are two distinct dimensions. A check can be "closed" with
      "conditional_accept"; merging them into one field would destroy that
      expressibility. result is nullable until status reaches closed.

    Quantity fields (qty_inspected / qty_accepted / qty_rejected):
      These are required — not optional — because without them it is impossible
      to calculate First Pass Yield (FPY = qty_accepted / qty_inspected) or
      rejection rates. An inspection record without quantities is analytically
      worthless for any real factory quality system.
      Constraint: qty_accepted + qty_rejected must equal qty_inspected.
      Enforced in the service layer (and validated in schemas).

    inspection_code:
      Auto-generated by the service layer using pattern QI-YYYY-NNNN.
      Never accepted as caller input — callers cannot choose or override codes.
      This ensures consistency, avoids duplicate or out-of-sequence codes,
      and matches how production_order_number is handled in the Production module.

    Production references (production_order_id, production_output_id, etc.):
      These are plain UUID columns — there are NO foreign key constraints to
      production tables. This preserves the Quality/Production module boundary
      (ADR-004). The service layer validates that referenced IDs belong to the
      current organization using direct SQL queries against production tables,
      without importing any Production model class into Quality code.
    """

    __tablename__ = "quality_checks"
    __table_args__ = (
        UniqueConstraint(
            "organization_id",
            "inspection_code",
            name="uq_quality_checks_org_inspection_code",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    organization_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("foundation_organizations.id"),
        nullable=False,
        index=True,
    )

    # Auto-generated by service layer. Pattern: QI-YYYY-NNNN. Never caller input.
    inspection_code: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
    )

    # Production context references — plain UUIDs, NO FK constraints (ADR-004).
    # At least one of production_order_id or production_output_id
    # should be provided. Validated as a soft warning in v0.1.
    production_order_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
        index=True,
    )
    production_order_item_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
    )
    production_output_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
        index=True,
    )

    check_datetime: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
    )
    check_type: Mapped[QualityCheckType] = mapped_column(
        SqlEnum(
            QualityCheckType,
            name="quality_check_type",
            values_callable=enum_values,
        ),
        nullable=False,
    )

    # Lifecycle state of the inspection process (open → under_inspection → closed).
    status: Mapped[QualityCheckStatus] = mapped_column(
        SqlEnum(
            QualityCheckStatus,
            name="quality_check_status",
            values_callable=enum_values,
        ),
        nullable=False,
        default=QualityCheckStatus.OPEN,
    )

    # Outcome of the inspection. NULL until the check reaches a concluded state.
    result: Mapped[QualityCheckResult | None] = mapped_column(
        SqlEnum(
            QualityCheckResult,
            name="quality_check_result",
            values_callable=enum_values,
        ),
        nullable=True,
    )

    # Quantity tracking — required for FPY and rejection-rate calculations.
    # Constraint: qty_accepted + qty_rejected == qty_inspected (enforced in service).
    qty_inspected: Mapped[int] = mapped_column(Integer, nullable=False)
    qty_accepted: Mapped[int] = mapped_column(Integer, nullable=False)
    qty_rejected: Mapped[int] = mapped_column(Integer, nullable=False)

    notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    # DB-level FK to foundation_users only; no import of User model into Quality.
    checked_by_user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("foundation_users.id"),
        nullable=False,
    )

    created_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
    )
    updated_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )


class QualityDefect(Base):
    """Observable defect found during a documented quality check.

    quality_check_id is required:
      A defect must always trace back to a formal QualityCheck. Without that
      parent check, the defect loses inspection context and analytical value.

    defect_count exists for defect-rate calculations:
      One inspection can find multiple units or instances with the same defect
      type. Storing the count lets QUAL-003 and later reporting calculate
      defect rates without duplicating identical rows.

    Production references:
      production_order_id, production_order_item_id, and production_output_id
      are plain optional UUIDs. They intentionally have no FK constraints to
      Production tables, preserving the Quality/Production module boundary.
    """

    __tablename__ = "quality_defects"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    organization_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("foundation_organizations.id"),
        nullable=False,
        index=True,
    )
    quality_check_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("quality_checks.id"),
        nullable=False,
        index=True,
    )

    # Optional convenience references to Production context: plain IDs only.
    production_order_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
        index=True,
    )
    production_order_item_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
    )
    production_output_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
        index=True,
    )

    defect_date: Mapped[date] = mapped_column(nullable=False, index=True)
    defect_category: Mapped[DefectCategory] = mapped_column(
        SqlEnum(
            DefectCategory,
            name="quality_defect_category",
            values_callable=enum_values,
        ),
        nullable=False,
        index=True,
    )
    severity: Mapped[DefectSeverity] = mapped_column(
        SqlEnum(
            DefectSeverity,
            name="quality_defect_severity",
            values_callable=enum_values,
        ),
        nullable=False,
        index=True,
    )
    defect_count: Mapped[int] = mapped_column(Integer, nullable=False, default=1)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    detected_by_user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("foundation_users.id"),
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
    )
    updated_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )


class QualityRejection(Base):
    """Formal disposition decision for non-conforming product.

    rejection_notes is required:
      Quality PRD BR-02 states that any rejection without a specified reason
      has zero analytical value. The enum classifies the reason; notes record
      the actual human justification for the decision.

    disposition vs disposition_status:
      disposition is the decision (hold, scrap, rework, return_to_process).
      disposition_status tracks whether that decision has actually been
      executed. Keeping them separate lets the system see open execution work.

    quantity_rejected is required:
      Rejection rate and FPY calculations need an explicit rejected quantity.
      A rejection without quantity cannot support meaningful quality KPIs.

    Quality context:
      At least one of quality_check_id or quality_defect_id should be present.
      This remains a v0.1 soft rule, but the fields allow every rejection to
      connect back to the QualityCheck -> QualityDefect -> QualityRejection chain.

    Production references:
      production_output_id and production_order_item_id are plain optional IDs
      with no FK constraints to Production tables, preserving module boundaries.
    """

    __tablename__ = "quality_rejections"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    organization_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("foundation_organizations.id"),
        nullable=False,
        index=True,
    )
    quality_check_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("quality_checks.id"),
        nullable=True,
        index=True,
    )
    quality_defect_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("quality_defects.id"),
        nullable=True,
        index=True,
    )

    # Optional Production context references: plain UUIDs, no FK constraints.
    production_output_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
        index=True,
    )
    production_order_item_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
    )

    rejection_date: Mapped[date] = mapped_column(nullable=False, index=True)
    rejection_reason: Mapped[RejectionReason] = mapped_column(
        SqlEnum(
            RejectionReason,
            name="quality_rejection_reason",
            values_callable=enum_values,
        ),
        nullable=False,
        index=True,
    )
    rejection_notes: Mapped[str] = mapped_column(Text, nullable=False)
    disposition: Mapped[Disposition] = mapped_column(
        SqlEnum(
            Disposition,
            name="quality_disposition",
            values_callable=enum_values,
        ),
        nullable=False,
        index=True,
    )
    disposition_status: Mapped[DispositionStatus] = mapped_column(
        SqlEnum(
            DispositionStatus,
            name="quality_disposition_status",
            values_callable=enum_values,
        ),
        nullable=False,
        default=DispositionStatus.PENDING,
        index=True,
    )
    quantity_rejected: Mapped[int] = mapped_column(Integer, nullable=False)
    unit: Mapped[str] = mapped_column(String(32), nullable=False)

    rejected_by_user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("foundation_users.id"),
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
    )
    updated_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )


