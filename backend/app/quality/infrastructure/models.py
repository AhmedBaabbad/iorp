class QualityRejection(Base):
    """Formal disposition decision for non-conforming product.

    rejection_notes is required:
      Quality PRD BR-02 states that any rejection without a specified reason
      has zero analytical value. The enum classifies the reason; notes record
      the actual human justification for the decision.

    disposition vs disposition_status:
      disposition is the decision (hold, scrap, rework, return_to_process).
      disposition_status tracks whether that decision has actually been
      executed. Keeping them separate lets the system see open execution work.

    quantity_rejected is required:
      Rejection rate and FPY calculations need an explicit rejected quantity.
      A rejection without quantity cannot support meaningful quality KPIs.

    Quality context:
      At least one of quality_check_id or quality_defect_id should be present.
      This remains a v0.1 soft rule, but the fields allow every rejection to
      connect back to the QualityCheck -> QualityDefect -> QualityRejection chain.

    Production references:
      production_order_item_id is a plain optional ID
      with no FK constraints to Production tables, preserving module boundaries.
    """

    __tablename__ = "quality_rejections"
    __table_args__ = (UniqueConstraint("organization_id", "rejection_code", name="uq_quality_rejections_org_code"),)

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    organization_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("foundation_organizations.id"),
        nullable=False,
        index=True,
    )
    quality_check_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("quality_checks.id"),
        nullable=True,
        index=True,
    )
    quality_defect_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("quality_defects.id"),
        nullable=True,
        index=True,
    )

    # Generated QR-YYYY-NNNN, never caller input.
    rejection_code: Mapped[str] = mapped_column(String(32), nullable=False)
    # Production context references: plain UUIDs, no FK constraints (ADR-004). The order is taken
    # from the check (or chosen for a manual rejection) so the order page and close gate find it.
    production_order_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True, index=True)
    production_order_item_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        nullable=True,
    )

    # QUAL-RET-001: a rejected part of returned goods (the shipping return and its line, plain UUIDs, no FK).
    return_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True, index=True)
    return_line_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True)
    rejection_date: Mapped[date] = mapped_column(nullable=False, index=True)
    rejection_reason: Mapped[RejectionReason] = mapped_column(
        SqlEnum(
            RejectionReason,
            name="quality_rejection_reason",
            values_callable=enum_values,
        ),
        nullable=False,
        index=True,
    )
    rejection_notes: Mapped[str] = mapped_column(Text, nullable=False)
    # NULL while pending: the disposition is a decision taken after the rejection is recorded.
    disposition: Mapped[Disposition | None] = mapped_column(
        SqlEnum(
            Disposition,
            name="quality_disposition",
            values_callable=enum_values,
        ),
        nullable=True,
        index=True,
    )
    disposition_status: Mapped[DispositionStatus] = mapped_column(
        SqlEnum(
            DispositionStatus,
            name="quality_disposition_status",
            values_callable=enum_values,
        ),
        nullable=False,
        default=DispositionStatus.PENDING,
        index=True,
    )
    quantity_rejected: Mapped[Decimal] = mapped_column(Numeric(14, 3), nullable=False)
    unit: Mapped[str] = mapped_column(String(32), nullable=False)
    decided_at: Mapped[datetime | None] = mapped_column(TZDateTime, nullable=True)
    decided_by_user_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("foundation_users.id"), nullable=True)
    decision_notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    # use_as_is only: who approved the concession (e.g. the customer's representative).
    concession_approved_by: Mapped[str | None] = mapped_column(String(255), nullable=True)
    executed_at: Mapped[datetime | None] = mapped_column(TZDateTime, nullable=True)
    executed_by_user_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), ForeignKey("foundation_users.id"), nullable=True)
    execution_notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    rejected_by_user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("foundation_users.id"),
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
    )
    updated_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )


class NonConformanceReport(Base):
    """A non-conformance and its corrective action (QUAL-NCR-002), from any source: incoming material from a supplier,
    production, the warehouse, a customer return or complaint.

    Numbered NCR-YYYY-NNNN from the quality counter. It moves open → investigation → action → verification → closed
    (or cancelled), see domain/ncr.py; each stage keeps what was found and decided, and who decided it.
    Sources are plain references, no foreign keys into other modules (ADR-004): the quality check or rejection that
    raised it, a production order, a shipping return, a supplier (named until the procurement module lists them).
    """

    __tablename__ = "non_conformance_reports"
    __table_args__ = (UniqueConstraint("organization_id", "report_number", name="uq_non_conformance_reports_org_report_number"),
                      Index("ix_non_conformance_reports_org_status", "organization_id", "status"))

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    organization_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("foundation_organizations.id"), nullable=False, index=True)
    report_number: Mapped[str] = mapped_column(String(32), nullable=False)
    report_date: Mapped[date] = mapped_column(nullable=False, index=True)
