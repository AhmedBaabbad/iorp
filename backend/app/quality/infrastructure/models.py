class NonConformanceItem(Base):
    """Affected element or line item within a non-conformance report.

    NCR items live in Quality for v0.1:
      NCR is a Quality sub-domain in the approved scaffold, not a separate
      backend/app/ncr module yet.

    Tenant scope cascades via parent report:
      Items intentionally do not carry organization_id. Every item operation
      validates the parent NonConformanceReport against the current tenant.

    issue_description is required:
      An item without a specific description of what is non-conforming has no
      traceability value for later investigation or NCR item review.

    Parent status guard:
      The service layer blocks creating or updating items when the parent NCR
      report is closed. This is a simple guard, not a workflow engine.
    """

    __tablename__ = "non_conformance_items"
    __table_args__ = (
        UniqueConstraint(
            "non_conformance_report_id",
            "line_no",
            name="uq_non_conformance_items_report_line_no",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    non_conformance_report_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("non_conformance_reports.id"),
        nullable=False,
        index=True,
    )
    line_no: Mapped[int] = mapped_column(Integer, nullable=False)
    item_reference: Mapped[str | None] = mapped_column(String(255), nullable=True)
    item_name: Mapped[str] = mapped_column(String(255), nullable=False)
    quantity_affected: Mapped[Decimal | None] = mapped_column(Numeric(14, 2), nullable=True)
    unit: Mapped[str | None] = mapped_column(String(32), nullable=True)
    issue_description: Mapped[str] = mapped_column(Text, nullable=False)
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
    )
    updated_at: Mapped[datetime] = mapped_column(
        TZDateTime,
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )
